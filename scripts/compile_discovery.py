def main() -> None:
    db = Database("data/restaurants.json").load()
    total = 0
    for batch in BATCHES:
        entries = [
            {
                "name": name,
                "city": city,
                "district": district,
                "address": address,
                "cuisine": cuisine,
                "source": batch["source"],
                "list_name": batch["list_name"],
            }
            for name, city, district, address, cuisine in batch["items"]
        ]
        summary = import_list_records(entries, db)
        total += summary["imported"]
        print(f"{batch['list_name'][:20]}…: 导入{summary['imported']} 跳过{summary['skipped_existing']}")
    db.save()
    print(f"本轮共导入 {total} 家，数据库现共 {len(db)} 家")


if __name__ == "__main__":
    main()
